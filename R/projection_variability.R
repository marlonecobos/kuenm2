#' Explores variance coming from distinct sources in model predictions
#'
#' @description
#' Calculates variance in model predictions, distinguishing
#' between the different sources of variation. Potential sources include
#' replicates, model parameterizations, and general circulation models (GCMs).
#'
#' @usage
#' projection_variability(model_projections, from_replicates = TRUE,
#'                        from_parameters = TRUE, from_gcms = TRUE,
#'                        consensus = "median", write_files = FALSE,
#'                        output_dir = NULL, return_rasters = TRUE,
#'                        parallel = FALSE, ncores = NULL,
#'                        progress_bar = FALSE, progress_type = "timer",
#'                        use_lb = FALSE, verbose = TRUE, overwrite = FALSE)
#'
#' @param model_projections a `model_projections` object generated by the
#' \code{\link{project_selected}}() function. This object contains the file
#' paths to the raster projection results and the thresholds used for binarizing
#' the predictions.
#' @param from_replicates (logical) whether to compute the variance originating
#' from replicates. Default is TRUE.
#' @param from_parameters (logical) whether to compute the variance originating
#' from model parameterizations. Default is TRUE.
#' @param from_gcms (logical) whether to compute the variance originating from
#' general circulation models (GCMs). Default is TRUE.
#' @param consensus (character) the consensus measure to use for calculating
#' variability across models and GCMs. Available options are `'median'` and
#' `'mean'`. Default is `'median'`.
#' @param write_files (logical) whether to write the raster files containing
#' the computed variance to disk. Default is FALSE.
#' @param output_dir (character) the directory path where the resulting raster
#' files containing the computed variance will be saved. Only relevant if
#' `write_files = TRUE`. Default is NULL.
#' @param return_rasters (logical) whether to return a list containing all the
#' SpatRasters with the computed variance. Default is TRUE.
#' @param parallel (logical) whether to compute variability across scenarios in
#' parallel. Default is FALSE.
#' @param ncores (numeric) number of cores to use for parallel processing.
#' Default is NULL and uses available cores - 1. Only applicable if
#' `parallel = TRUE`.
#' @param progress_bar (logical) whether to display a progress bar during
#' processing. Default is FALSE.
#' @param progress_type (character) type of the progress bar. See
#' `pbapply::pbtypes()` for available progress bar types depending on operating
#' system. Default is `"timer"`.
#' @param use_lb (logical) whether to use load balancing when running in
#' parallel. Default is FALSE.
#' @param verbose (logical) whether to display messages during processing.
#' Default is TRUE.
#' @param overwrite (logical) whether to overwrite SpatRaster files if they
#' already exist. Only applicable if `write_files = TRUE`. Default is FALSE.
#'
#' @return
#' An object of class `variability_projections`. If `return_rasters = TRUE`,
#' the function returns a list containing the SpatRasters with the computed
#' variances, categorized by replicate, model, and GCMs, along with
#' `root_directory`. If `write_files = TRUE`, the object can be used to import
#' these files later with [import_results()].
#'
#' @export
#'
#' @importFrom terra rast nlyr mean app writeRaster wrap unwrap
#' @importFrom parallel makeCluster stopCluster detectCores
#' @importFrom pbapply pboptions pblapply
#'
#' @seealso
#' [organize_future_worldclim()], [prepare_projection()], [project_selected()],
#' [import_results()]
#'
#' @examples
#' # Step 1: Organize variables for current projection
#' ## Import current variables (used to fit models)
#' var <- terra::rast(system.file("extdata", "Current_variables.tif",
#'                                package = "kuenm2"))
#'
#' ## Create a folder in a temporary directory to copy the variables
#' out_dir_current <- file.path(tempdir(), "Current_raw5")
#' dir.create(out_dir_current, recursive = TRUE)
#'
#' ## Save current variables in temporary directory
#' terra::writeRaster(var, file.path(out_dir_current, "Variables.tif"))
#'
#' # Step 2: Organize future climate variables (example with WorldClim)
#' ## Directory containing the downloaded future climate variables (example)
#' in_dir <- system.file("extdata", package = "kuenm2")
#'
#' ## Create a folder in a temporary directory to copy the future variables
#' out_dir_future <- file.path(tempdir(), "Future_raw5")
#'
#' ## Organize and rename the future climate data (structured by year and GCM)
#' ### 'SoilType' will be appended as a static variable in each scenario
#' organize_future_worldclim(input_dir = in_dir, output_dir = out_dir_future,
#'                           name_format = "bio_", static_variables = var$SoilType)
#'
#' # Step 3: Prepare data to run multiple projections
#' ## An example with maxnet models
#' ## Import example of fitted_models (output of fit_selected())
#' data(fitted_model_maxnet, package = "kuenm2")
#'
#' ## Prepare projection data using fitted models to check variables
#' pr <- prepare_projection(models = fitted_model_maxnet,
#'                          present_dir = out_dir_current,
#'                          future_dir = out_dir_future,
#'                          future_period = "2041-2060",
#'                          future_pscen = "ssp126",
#'                          future_gcm = c("ACCESS-CM2", "MIROC6"),
#'                          raster_pattern = ".tif*")
#'
#' # Step 4: Run multiple model projections
#' ## A folder to save projection results
#' out_dir <- file.path(tempdir(), "Projection_results/maxnet3")
#' dir.create(out_dir, recursive = TRUE)
#'
#' ## Project selected models to multiple scenarios
#' p <- project_selected(models = fitted_model_maxnet, projection_data = pr,
#'                       out_dir = out_dir)
#'
#' # Step 5: Compute variance from distinct sources
#' v <- projection_variability(model_projections = p, from_replicates = FALSE)
#'
#' terra::plot(v$Present$from_parameters)  # From models with distinct parameters
#' terra::plot(v$`Future_2041-2060_ssp126`$from_parameters)  # From models
#' terra::plot(v$`Future_2041-2060_ssp126`$from_gcms)  # From GCMs

projection_variability <- function(model_projections,
                                   from_replicates = TRUE,
                                   from_parameters = TRUE,
                                   from_gcms = TRUE,
                                   consensus = "median",
                                   write_files = FALSE,
                                   output_dir = NULL,
                                   return_rasters = TRUE,
                                   parallel = FALSE,
                                   ncores = NULL,
                                   progress_bar = FALSE,
                                   progress_type = "timer",
                                   use_lb = FALSE,
                                   verbose = TRUE,
                                   overwrite = FALSE) {
  # Check data
  if (missing(model_projections)) {
    stop("Argument 'model_projections' must be defined.")
  }
  if (!inherits(model_projections, "model_projections")) {
    stop("Argument 'model_projections' must be a 'model_projections' object.")
  }
  if (!any(c(from_replicates, from_parameters, from_gcms))) {
    stop("At least one of 'from_replicates', 'from_parameters', or 'from_gcms' must be TRUE.")
  }
  if (!inherits(consensus, "character") || length(consensus) != 1L) {
    stop("Argument 'consensus' must be a single 'character' value ('median' or 'mean').")
  }
  if (!consensus %in% c("median", "mean")) {
    stop("Invalid 'consensus' provided. Options are: 'median' or 'mean'.")
  }
  if (write_files && is.null(output_dir)) {
    stop("If 'write_files' = TRUE, 'output_dir' must be specified.")
  }
  if (write_files && !inherits(output_dir, "character")) {
    stop("Argument 'output_dir' must be a 'character'.")
  }
  if (!return_rasters && !write_files) {
    stop("'return_rasters' and 'write_files' cannot both be FALSE.")
  }

  # Create directory if necessary
  if (write_files) {
    out_dir <- file.path(output_dir, "variance")
    if (!dir.exists(out_dir)) {
      dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)
    }
  } else {
    out_dir <- NULL
  }

  # Get data
  d <- model_projections[["paths"]]
  if (!"Scenario" %in% names(d)) {
    d$Scenario <- NA_character_
  }

  # Determine consensus layer name (handles models without replicates)
  is_full_model <- identical(names(model_projections$thresholds[[1]])[1], "Full_model")
  cons_layer <- if (is_full_model) "Full_model" else consensus

  # Get unique combinations of Time, Period, and Scenario
  uc <- unique(d[, c("Time", "Period", "Scenario"), drop = FALSE])
  n_uc <- nrow(uc)

  if (n_uc == 1L && parallel) {
    parallel <- FALSE
  }

  # Setup progress bar safely for CRAN
  old_pbopt <- pbapply::pboptions(
    type = if (progress_bar) progress_type else "none",
    use_lb = use_lb
  )
  on.exit(pbapply::pboptions(old_pbopt), add = TRUE)

  if (parallel) {
    if (is.null(ncores)) {
      ncores <- max(1L, parallel::detectCores() - 1L, na.rm = TRUE)
      chk <- Sys.getenv("_R_CHECK_LIMIT_CORES_", "")
      if (nzchar(chk) && chk == "TRUE") {
        ncores <- min(ncores, 2L)
      }
    }
    if (n_uc < ncores) {
      ncores <- n_uc
    }
    cl <- parallel::makeCluster(ncores)
    on.exit(parallel::stopCluster(cl), add = TRUE)
    verbose <- FALSE
  } else {
    cl <- NULL
  }

  # Iteration over combinations
  res <- pbapply::pblapply(
    X = seq_len(n_uc),
    FUN = function(z, uc, d, n_uc, from_replicates, from_parameters, from_gcms,
                   cons_layer, write_files, out_dir, overwrite, return_rasters,
                   verbose, is_parallel) {
      time <- uc$Time[z]
      period <- uc$Period[z]
      scenario <- uc$Scenario[z]

      # Exact NA-safe matching for Time, Period, and Scenario
      idx_time <- if (is.na(time)) is.na(d$Time) else (!is.na(d$Time) & d$Time == time)
      idx_period <- if (is.na(period)) is.na(d$Period) else (!is.na(d$Period) & d$Period == period)
      idx_scen <- if (is.na(scenario)) is.na(d$Scenario) else (!is.na(d$Scenario) & d$Scenario == scenario)

      paths <- d$output_path[idx_time & idx_period & idx_scen]
      n_paths <- length(paths)

      # By replicate
      if (from_replicates) {
        if (verbose) {
          message("\nCalculating variability from distinct replicates: scenario ",
                  z, " of ", n_uc)
        }
        var_rep <- terra::rast(lapply(paths, var_models_rep_by_gcm))
        if (n_paths > 1L) {
          var_rep <- terra::mean(var_rep)
        }
        names(var_rep) <- "from_replicates"
      } else {
        var_rep <- NULL
      }

      # By model parameterization
      if (from_parameters) {
        if (verbose) {
          message("Calculating variability from distinct models: scenario ",
                  z, " of ", n_uc)
        }
        var_model <- terra::rast(lapply(paths, var_models_model_by_gcm, cons_layer))
        if (n_paths > 1L) {
          var_model <- terra::mean(var_model)
        }
        names(var_model) <- "from_parameters"
      } else {
        var_model <- NULL
      }

      # By GCM
      if (from_gcms && !is.na(period) && period != "Present" && n_paths > 1L) {
        if (verbose) {
          message("Calculating variability from distinct GCMs: scenario ",
                  z, " of ", n_uc)
        }
        var_gcm <- var_models_across_gcm(paths = paths, consensus = cons_layer)
        names(var_gcm) <- "from_gcms"
      } else {
        var_gcm <- NULL
      }

      var_list <- Filter(Negate(is.null), list(
        from_replicates = var_rep,
        from_parameters = var_model,
        from_gcms = var_gcm
      ))
      all_var <- terra::rast(var_list)

      # Write results
      if (write_files) {
        nr <- gsub("_NA", "", paste(time, period, scenario, sep = "_"))
        if (nr == "Present_Present_Present") {
          nr <- "Present"
        }
        terra::writeRaster(all_var,
                           filename = file.path(out_dir, paste0(nr, ".tif")),
                           overwrite = overwrite)
      }

      if (return_rasters) {
        if (is_parallel) {
          return(terra::wrap(all_var))
        }
        return(all_var)
      } else {
        return(invisible(NULL))
      }
    },
    uc = uc,
    d = d,
    n_uc = n_uc,
    from_replicates = from_replicates,
    from_parameters = from_parameters,
    from_gcms = from_gcms,
    cons_layer = cons_layer,
    write_files = write_files,
    out_dir = out_dir,
    overwrite = overwrite,
    return_rasters = return_rasters,
    verbose = verbose,
    is_parallel = parallel,
    cl = cl
  )

  if (return_rasters) {
    if (parallel) {
      res <- lapply(res, terra::unwrap)
    }
    names(res) <- gsub("Present_Present_Present", "Present",
                       gsub("_NA", "",
                            paste(uc$Time, uc$Period, uc$Scenario, sep = "_")))
    res[["root_directory"]] <- out_dir
  } else {
    res <- list("root_directory" = out_dir)
  }

  class(res) <- "variability_projections"

  # Save variability_projections object (only root directory)
  if (write_files) {
    res_to_write <- res["root_directory"]
    class(res_to_write) <- "variability_projections"
    saveRDS(res_to_write,
            file.path(out_dir, "variability_projections.rds"))
  }

  return(res)
}
